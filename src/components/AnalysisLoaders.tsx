/**
 * Waiting states for a dispatched analysis run.
 *
 * Both runs answer over the chat socket rather than the HTTP response, so
 * these stay up until a socket event for the session arrives. The plan loader
 * shows a small set of status messages while the request is running; it does
 * not claim a completion percentage or finish the request on a timer.
 */
import { useEffect, useState } from "react";
import { Check, Clock, X } from "lucide-react";
import { useLanguage } from "../context/LanguageContext";

function Shimmer({ className = "", style }: { className?: string; style?: React.CSSProperties }) {
  return <div className={`animate-pulse rounded bg-slate-200/80 ${className}`} style={style} />;
}

/** How long each tip stays up before the next one takes its place. */
const TIP_INTERVAL_MS = 7000;

/** Kept beside the interval so the rotation cannot drift out of range. */
const TIP_COUNT = 10;

/**
 * What to read while the agents work.
 *
 * A run takes minutes, and a progress bar that cannot honestly report progress
 * just reads as a stall. These explain what the agents are doing and what the
 * reader can do with the result, which is the one thing this wait is good for.
 */
function LoadingTips() {
  const { t } = useLanguage();
  const [index, setIndex] = useState(0);

  const tips = [
    t("analysisLoaders.tip1", {
      defaultValue:
        "Need a quick answer? Switch to Chat mode for faster, more direct responses.",
    }),
    t("analysisLoaders.tip2", {
      defaultValue:
        "Every report is generated by multiple agents that collect and analyze relevant data.",
    }),
    t("analysisLoaders.tip3", {
      defaultValue:
        "You can customize what each agent should look for and what it should ignore on the planning screen.",
    }),
    t("analysisLoaders.tip4", {
      defaultValue:
        "When multiple agents generate a report, you can find their individual answers in the ‘Specialist’ menu on the left sidebar.",
    }),
    t("analysisLoaders.tip5", {
      defaultValue:
        "Scroll down on the home page to quickly access your recent reports.",
    }),
    t("analysisLoaders.tip6", {
      defaultValue:
        "Have a question for a specific agent? Open the ‘Specialist’ menu, select an agent, and ask your question.",
    }),
    t("analysisLoaders.tip7", {
      defaultValue:
        "The more relevant data you connect to the system, the more comprehensive and useful your results can be.",
    }),
    t("analysisLoaders.tip8", {
      defaultValue:
        "The system can generate in-depth answers to complex questions by analyzing data across multiple sources.",
    }),
    t("analysisLoaders.tip9", {
      defaultValue:
        "Want to verify an answer? Expand ‘How the data was found’ at the bottom of the report card to review the supporting evidence.",
    }),
    t("analysisLoaders.tip10", {
      defaultValue:
        "Report generation may take a few minutes, but compared with doing the same work manually, it takes just a fraction of the time.",
    }),
  ];

  useEffect(() => {
    const timer = window.setInterval(() => {
      setIndex((current) => (current + 1) % TIP_COUNT);
    }, TIP_INTERVAL_MS);
    return () => window.clearInterval(timer);
  }, []);

  return (
    <div className="flex flex-col items-center gap-2 px-4 py-1 text-center">
      <span className="text-[10px] font-semibold uppercase tracking-[0.16em] text-slate-500">
        {t("analysisLoaders.tipLabel", { defaultValue: "Tip" })}
      </span>
      {/* Keyed so the fade restarts on each tip; nothing moves, only opacity.
          The reserved height is what keeps the skeleton below from shifting
          when a longer tip takes a line more than the one before it. */}
      <div className="flex min-h-[4.5rem] max-w-md items-center justify-center sm:min-h-[4rem]">
        <p
          key={index}
          aria-live="polite"
          className="text-[13px] italic leading-relaxed text-slate-600 animate-in fade-in duration-500 sm:text-sm"
        >
          {tips[index]}
        </p>
      </div>
    </div>
  );
}

